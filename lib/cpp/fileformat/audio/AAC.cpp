	IAudioStream* AAC_OpenRawStream(
		StorageTrait& storage,
		const AACRawFrame* frames,
		uint32 frame_count,
		uint32 sample_rate,
		uint32 channels,
		trait::Malloc& allocator
	) {
		if (!frames || frame_count == 0 || sample_rate == 0) return nullptr;
		void* mem = allocator.allocate(sizeof(AACStream), 3);
		if (!mem) return nullptr;
		// The caller owns the table: MP4 keeps it for its sample-to-time mapping.
		return new (mem) AACStream(storage, frames, frame_count, 0, false,
								   sample_rate, channels, allocator);
	}

	const char* AACCodec::GetName() const { return "AAC"; }

	AudioContainerFormat AACCodec::GetFormat() const { return AudioContainerFormat::AAC; }

	const char* const* AACCodec::GetExtensions() const { return AAC_EXTENSIONS; }

	AudioResult AACCodec::Probe(StorageTrait& storage, bool& matched) const {
		matched = false;
		byte h[7];
		if (!StorageReadExact(storage, 0, h, sizeof(h))) return AudioResult::IoError;
		uint32 rate = 0, channels = 0, frame_len = 0;
		if (!AAC_ParseADTSHeader(h, rate, channels, frame_len)) return AudioResult::OK;
		matched = true;
		return AudioResult::OK;
	}

	AudioResult AACCodec::ReadInfo(StorageTrait& storage, AudioInfo& outInfo) const {
		byte h[7];
		if (!StorageReadExact(storage, 0, h, sizeof(h))) return AudioResult::IoError;
		uint32 rate = 0, channels = 0, frame_len = 0;
		if (!AAC_ParseADTSHeader(h, rate, channels, frame_len)) return AudioResult::InvalidFormat;
		outInfo = AudioInfo{};
		outInfo.format.sample_format = AudioSampleFormat::S16LE;
		outInfo.format.channels = (uint16)(channels ? channels : 2);
		outInfo.format.sample_rate = rate;
		outInfo.bitsPerSample = 16;
		outInfo.containerFormat = AudioContainerFormat::AAC;
		return AudioResult::OK;
	}

	AudioResult AACCodec::OpenStream(
		StorageTrait& storage,
		IAudioStream*& outStream,
		trait::Malloc& allocator
	) const {
		outStream = nullptr;
		byte h[7];
		if (!StorageReadExact(storage, 0, h, sizeof(h))) return AudioResult::IoError;
		uint32 rate = 0, channels = 0, first_len = 0;
		if (!AAC_ParseADTSHeader(h, rate, channels, first_len)) return AudioResult::InvalidFormat;

		// Walk the ADTS chain once so the stream can be seeked by frame index.
		uint32 capacity = 1024;
		AACRawFrame* frames = (AACRawFrame*)allocator.allocate(capacity * sizeof(AACRawFrame), 3);
		if (!frames) return AudioResult::OutOfMemory;
		uint32 count = 0;
		uint64 pos = 0;
		for (;;) {
			byte fh[7];
			if (!StorageReadExact(storage, pos, fh, sizeof(fh))) break;
			uint32 r = 0, c = 0, len = 0;
			if (!AAC_ParseADTSHeader(fh, r, c, len)) break;
			if (count == capacity) {
				uint32 bigger_cap = capacity * 2;
				AACRawFrame* bigger = (AACRawFrame*)allocator.allocate(bigger_cap * sizeof(AACRawFrame), 3);
				if (!bigger) break;
				MemCopyN(bigger, frames, capacity * sizeof(AACRawFrame));
				allocator.deallocate(frames, capacity * sizeof(AACRawFrame));
				frames = bigger;
				capacity = bigger_cap;
			}
			// Skip the header: the decoder expects the raw access unit.
			frames[count].offset = pos + 7;
			frames[count].size = len - 7;
			++count;
			pos += len;
		}
		if (count == 0) {
			allocator.deallocate(frames, capacity * sizeof(AACRawFrame));
			return AudioResult::InvalidFormat;
		}

		void* mem = allocator.allocate(sizeof(AACStream), 3);
		if (!mem) {
			allocator.deallocate(frames, capacity * sizeof(AACRawFrame));
			return AudioResult::OutOfMemory;
		}
		// The table was built here, so the stream releases it with itself.
		outStream = new (mem) AACStream(storage, frames, count, capacity, true,
										rate, channels, allocator);
		return AudioResult::OK;
	}

