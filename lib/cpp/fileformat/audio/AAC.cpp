static inline float aac_fabs(float x) {
	return (x < 0.0f) ? -x : x;
}

static inline float aac_pow2_quarter(int exp_quarter) {
	int n = exp_quarter >> 2;
	int rem = exp_quarter & 3;
	static const float rem_table[4] = { 1.0f, 1.189207115f, 1.414213562f, 1.681792831f };
	float base = rem_table[rem];
	if (n >= 0) {
		while (n > 30) { base *= 1073741824.0f; n -= 30; }
		return base * (float)(1ULL << n);
	} else {
		int neg_n = -n;
		while (neg_n > 30) { base /= 1073741824.0f; neg_n -= 30; }
		return base / (float)(1ULL << neg_n);
	}
}

static inline float aac_pow43(float val) {
	if (val <= 0.0f) return 0.0f;
	if (val == 1.0f) return 1.0f;
	static const float pow43_small[17] = {
		0.000000f, 1.000000f, 2.519842f, 4.326749f,
		6.349604f, 8.549880f, 10.902724f, 13.390518f,
		16.000000f, 18.720754f, 21.544347f, 24.463781f,
		27.473142f, 30.567343f, 33.741992f, 36.993181f,
		40.317474f
	};
	int ival = (int)(val + 0.5f);
	if (ival >= 0 && ival <= 16 && (float)ival == val) {
		return pow43_small[ival];
	}
	double r = 4.0;
	for (int iter = 0; iter < 6; ++iter) {
		r = (2.0 * r + (double)val / (r * r)) / 3.0;
	}
	return (float)((double)val * r);
}

struct AACBitReader {
	const uint8* buf;
	size_t len;
	size_t bit_pos;
};

static inline void AACBitReader_Init(AACBitReader* br, const uint8* buf, size_t len) {
	br->buf = buf;
	br->len = len;
	br->bit_pos = 0;
}

static inline uint32 AACBitReader_GetBits(AACBitReader* br, int n) {
	if (n <= 0) return 0;
	uint32 val = 0;
	for (int i = 0; i < n; ++i) {
		size_t byte_idx = br->bit_pos >> 3;
		int bit_idx = 7 - (int)(br->bit_pos & 7);
		int bit = 0;
		if (byte_idx < br->len) {
			bit = (br->buf[byte_idx] >> bit_idx) & 1;
			br->bit_pos++;
		} else {
			br->bit_pos = br->len * 8;
		}
		val = (val << 1) | bit;
	}
	return val;
}

static inline int AACBitReader_Get1Bit(AACBitReader* br) {
	size_t byte_idx = br->bit_pos >> 3;
	int bit_idx = 7 - (int)(br->bit_pos & 7);
	int bit = 0;
	if (byte_idx < br->len) {
		bit = (br->buf[byte_idx] >> bit_idx) & 1;
		br->bit_pos++;
	} else {
		br->bit_pos = br->len * 8;
	}
	return bit;
}

static inline size_t AACBitReader_BitsLeft(const AACBitReader* br) {
	size_t total_bits = br->len * 8;
	return (br->bit_pos < total_bits) ? (total_bits - br->bit_pos) : 0;
}

static inline uint32 AACBitReader_PeekBits(AACBitReader* br, int n) {
	size_t save = br->bit_pos;
	uint32 val = AACBitReader_GetBits(br, n);
	br->bit_pos = save;
	return val;
}

static inline void AACBitReader_SkipBits(AACBitReader* br, int n) {
	br->bit_pos += n;
}

static int AAC_DecodeHuffman(AACBitReader* br, const uint16_t* codes, const uint8_t* bits, int size) {
	for (int i = 0; i < size; ++i) {
		int b = bits[i];
		if (b > 0) {
			uint32 peek = AACBitReader_PeekBits(br, b);
			if (peek == codes[i]) {
				AACBitReader_SkipBits(br, b);
				return i;
			}
		}
	}
	return -1;
}

static int AAC_DecodeScalefactor(AACBitReader* br) {
	for (int i = 0; i < 121; ++i) {
		int b = s_aac_scalefactor_bits[i];
		if (b > 0) {
			uint32 peek = AACBitReader_PeekBits(br, b);
			if (peek == s_aac_scalefactor_code[i]) {
				AACBitReader_SkipBits(br, b);
				return i - 60;
			}
		}
	}
	return 0;
}

// Half windows of the four AAC window shapes (ISO/IEC 14496-3 4.6.11.3.2), indexed by
// window_shape: 0 is the sine window, 1 the Kaiser-Bessel derived window.  Only the sine
// window used to exist here, while real streams almost always signal window_shape = 1.
static float aac_win_long[2][1024];
static float aac_win_short[2][128];
static float aac_frame_win[2048];
static float aac_cos_lut[8192];
static bool aac_win_inited = false;

// Kaiser-Bessel derived window (ISO/IEC 14496-3 4.6.11.3.2): the
// normalised running sum of a Kaiser window, with I0 evaluated as a truncated series.
static void AAC_KbdWindow(float* window, double alpha, int n) {
	const double pi = 3.14159265358979323846;
	const double alpha2 = (alpha * pi / n) * (alpha * pi / n);
	double sum = 0.0;
	for (int i = 0; i < n; ++i) {
		const double tmp = (double)i * (n - i) * alpha2;
		double bessel = 1.0;
		for (int j = 50; j > 0; --j) bessel = bessel * tmp / ((double)j * j) + 1.0;
		sum += bessel;
		window[i] = (float)sum;
	}
	sum += 1.0;
	for (int i = 0; i < n; ++i) window[i] = (float)dblsqrt((double)window[i] / sum);
}

static void InitAACWindow() {
	if (aac_win_inited) return;
	const double pi = 3.14159265358979323846;
	for (int i = 0; i < 1024; ++i) aac_win_long[0][i] = (float)dblsin(pi / 2048.0 * (i + 0.5));
	for (int i = 0; i < 128; ++i) aac_win_short[0][i] = (float)dblsin(pi / 256.0 * (i + 0.5));
	AAC_KbdWindow(aac_win_long[1], 4.0, 1024);
	AAC_KbdWindow(aac_win_short[1], 6.0, 128);
	/* Precompute discrete cosine LUT for 2048-point IMDCT:
	 * ISO/IEC 14496-3 Clause 4.5.2.8.2:
	 * Angle theta(n, k) = (2*pi / N) * (n + 0.5 + N/4) * (k + 0.5)
	 * For N = 2048: theta(n, k) = (pi / 4096) * (2n + 1025) * (2k + 1).
	 * Period 2*pi corresponds to 8192 discrete angle bins. */
	for (int i = 0; i < 8192; ++i) {
		aac_cos_lut[i] = (float)dblcos(2.0 * pi / 8192.0 * (double)i);
	}
	aac_win_inited = true;
}

// Assemble the 2048-sample analysis window of one frame from the two half windows.  A start or
// stop sequence splices a short window into an otherwise flat half, which is what lets a long
// block abut the eight short ones.
static void AAC_BuildFrameWindow(int win_seq, int win_shape) {
	const float* L = aac_win_long[win_shape & 1];
	const float* S = aac_win_short[win_shape & 1];
	if (win_seq == 1) {                          // LONG_START_SEQUENCE
		for (int i = 0; i < 1024; ++i) aac_frame_win[i] = L[i];
		for (int i = 1024; i < 1472; ++i) aac_frame_win[i] = 1.0f;
		for (int i = 0; i < 128; ++i) aac_frame_win[1472 + i] = S[127 - i];
		for (int i = 1600; i < 2048; ++i) aac_frame_win[i] = 0.0f;
	} else if (win_seq == 3) {                   // LONG_STOP_SEQUENCE
		for (int i = 0; i < 448; ++i) aac_frame_win[i] = 0.0f;
		for (int i = 0; i < 128; ++i) aac_frame_win[448 + i] = S[i];
		for (int i = 576; i < 1024; ++i) aac_frame_win[i] = 1.0f;
		for (int i = 1024; i < 2048; ++i) aac_frame_win[i] = L[2047 - i];
	} else {                                     // ONLY_LONG_SEQUENCE
		for (int i = 0; i < 1024; ++i) {
			aac_frame_win[i] = L[i];
			aac_frame_win[2047 - i] = L[i];
		}
	}
}

/* ISO/IEC 14496-3 Clause 4.5.2.8.2: IMDCT synthesis for N = 2048
 * x_n = (2 / N) * sum_{k=0}^{N/2 - 1} X_k * cos((2*pi/N)*(n + 0.5 + N/4)*(k + 0.5))
 * Normalization factor (2 / N) = (2 / 2048) = (1 / 1024). */
static void AAC_IMDCT_2048(const float* in, float* out) {
	const int N = 2048;
	const int N2 = 1024;
	const float inv_N = 1.0f / 1024.0f; // 2.0 / N = 2.0 / 2048 = 1.0 / 1024

	for (int n = 0; n < N; ++n) {
		float sum = 0.0f;
		int step = 2 * n + 1025;
		int idx = step & 8191;
		int step2 = (step * 2) & 8191;
		for (int k = 0; k < N2; ++k) {
			sum += in[k] * aac_cos_lut[idx];
			idx = (idx + step2) & 8191;
		}
		out[n] = sum * inv_N;
	}
}

// Temporal noise shaping (ISO/IEC 14496-3 4.6.9).  The filters are parsed with the side
// information and applied to the spectrum after mid/side decoding and before the filterbank,
// which is where the decoder applies them: after mid/side, before the filterbank.
struct AACTnsFilter {
	int length;
	int order;
	int direction;
	int coef_compress;
	int coef[32];
};

struct AACTns {
	int n_filt;
	int coef_res;
	AACTnsFilter filt[8];
};

// Transmitted filter coefficients -> LPC coefficients (ISO/IEC 14496-3 4.6.9.3, tns_decode_coef).
static void AAC_TnsDecodeCoef(int order, int coef_res_bits, int coef_compress,
							  const int* coef, float* a) {
	static const int sgn_mask[3] = { 0x2, 0x4, 0x8 };
	static const int neg_mask[3] = { ~0x3, ~0x7, ~0xf };
	int tmp[32];
	float tmp2[32];
	float b[32];

	const int coef_res2 = coef_res_bits - coef_compress;
	const int s_mask = sgn_mask[coef_res2 - 2];
	const int n_mask = neg_mask[coef_res2 - 2];
	const double half_pi = 1.57079632679489661923;
	const double iqfac = ((double)(1 << (coef_res_bits - 1)) - 0.5) / half_pi;
	const double iqfac_m = ((double)(1 << (coef_res_bits - 1)) + 0.5) / half_pi;

	for (int i = 0; i < order; ++i) {
		tmp[i] = (coef[i] & s_mask) ? (coef[i] | n_mask) : coef[i];
		tmp2[i] = (float)dblsin(tmp[i] / ((tmp[i] >= 0) ? iqfac : iqfac_m));
	}

	a[0] = 1.0f;
	for (int m = 1; m <= order; ++m) {
		for (int i = 1; i < m; ++i) b[i] = a[i] + tmp2[m - 1] * a[m - i];
		for (int i = 1; i < m; ++i) a[i] = b[i];
		a[m] = tmp2[m - 1];
	}
}

// y(n) = x(n) - lpc[1]*y(n-1) - ... - lpc[order]*y(n-order); the state starts at zero and the
// result overwrites the input (ISO/IEC 14496-3 4.6.9.3, tns_ar_filter).
static void AAC_TnsArFilter(float* spectrum, int size, int inc, const float* lpc, int order) {
	float y[32];
	if (order > 32) order = 32;
	for (int i = 0; i < order; ++i) y[i] = 0.0f;
	int idx = 0;
	for (int n = 0; n < size; ++n, idx += inc) {
		float x = spectrum[idx];
		for (int k = 0; k < order; ++k) x -= lpc[k + 1] * y[k];
		for (int k = order - 1; k > 0; --k) y[k] = y[k - 1];
		y[0] = x;
		spectrum[idx] = x;
	}
}

static void AAC_TnsApply(float* spec, const AACTns* tns, int max_sfb) {
	// The long window of 48 kHz has 49 scalefactor bands; AAC-LC allows TNS over at most
	// TNS_MAX_BANDS = 40 of them and filter orders up to TNS_MAX_ORDER = 12 (ISO/IEC 14496-3
	// Tables 4.102 and 4.103).
	const int kNumSwb = 49;
	const int kMaxBands = 40;
	const int kMaxOrder = 12;
	int bottom = kNumSwb;
	for (int f = 0; f < tns->n_filt; ++f) {
		const AACTnsFilter& flt = tns->filt[f];
		int top = bottom;
		bottom = top - flt.length;
		if (bottom < 0) bottom = 0;
		int order = flt.order;
		if (order > kMaxOrder) order = kMaxOrder;
		if (order <= 0) continue;

		float lpc[32];
		AAC_TnsDecodeCoef(order, tns->coef_res + 3, flt.coef_compress, flt.coef, lpc);

		int b = bottom, t = top;
		if (b > kMaxBands) b = kMaxBands;
		if (t > kMaxBands) t = kMaxBands;
		if (b > max_sfb) b = max_sfb;
		if (t > max_sfb) t = max_sfb;
		int start = swb_offset_48000_1024[b];
		int end = swb_offset_48000_1024[t];
		int size = end - start;
		if (size <= 0) continue;

		int inc = 1;
		if (flt.direction) { inc = -1; start = end - 1; }
		AAC_TnsArFilter(spec + start, size, inc, lpc, order);
	}
}

struct AACChannelState {
	float overlap[1024];
};

struct AACDecoderState {
	AACChannelState ch[2];
};

static bool DecodeAAC_CPE(
	AACDecoderState* state,
	const uint8* data,
	size_t len,
	int16* pcm_out_interleaved
) {
	InitAACWindow();
	AACBitReader br;
	AACBitReader_Init(&br, data, len);

	int id = AACBitReader_GetBits(&br, 3);
	if (id != 1) return false;

	int tag = AACBitReader_GetBits(&br, 4);
	int common_win = AACBitReader_Get1Bit(&br);
	if (!common_win) return false;

	// ics_info (ISO/IEC 14496-3 Table 4.6).  A reserved bit precedes window_sequence, and a long
	// window carries predictor_data_present after max_sfb; skipping either one shifted every
	// following field by a bit and made the whole frame decode into noise.
	AACBitReader_Get1Bit(&br);                       // ics_reserved_bit
	int win_seq = AACBitReader_GetBits(&br, 2);
	int win_shape = AACBitReader_Get1Bit(&br);
	if (win_seq == 2) return false;                  // eight short windows, not implemented
	int max_sfb = AACBitReader_GetBits(&br, 6);
	// swb_offset_48000_1024 describes 49 long scalefactor bands, so swb_offsets[s + 1] would run
	// past the table for anything larger.
	if (max_sfb <= 0 || max_sfb > 49) return false;
	if (AACBitReader_Get1Bit(&br)) return false;     // predictor_data_present (AAC Main / LTP only)

	int ms_mask_present = AACBitReader_GetBits(&br, 2);
	uint8 ms_used[128] = { 0 };
	if (ms_mask_present == 1) {
		for (int sfb = 0; sfb < max_sfb; ++sfb) {
			ms_used[sfb] = AACBitReader_Get1Bit(&br);
		}
	} else if (ms_mask_present == 2) {
		for (int sfb = 0; sfb < max_sfb; ++sfb) ms_used[sfb] = 1;
	}

	uint8 sect_cb[2][128] = { 0 };
	int16 sf[2][128] = { 0 };
	float spec[2][1024] = { 0 };
	AACTns tns[2] = {};

	const uint16* swb_offsets = swb_offset_48000_1024;

	for (int ch = 0; ch < 2; ++ch) {
		int global_gain = AACBitReader_GetBits(&br, 8);
		int sfb = 0;
		while (sfb < max_sfb) {
			if (br.bit_pos >= br.len * 8) return false;
			int cb = AACBitReader_GetBits(&br, 4);
			int incr = 0;
			int len_code = 0;
			while ((len_code = AACBitReader_GetBits(&br, 5)) == 31) {
				incr += 31;
				if (br.bit_pos >= br.len * 8) return false;
			}
			incr += len_code;
			if (incr <= 0) return false;
			for (int k = 0; k < incr && sfb < max_sfb; ++k, ++sfb) {
				sect_cb[ch][sfb] = (uint8)cb;
			}
		}

		// Scalefactors are three independent differential chains: normal codebooks, noise bands
		// and intensity bands each have their own accumulator, and the first noise band sends its
		// gain as a plain 9-bit preamble instead of a code word (ISO/IEC 14496-3 4.6.3.3;
		// offset[3] and NOISE_PRE).  Feeding noise and intensity gains into the normal chain
		// shifted every later scalefactor, which is what made the level of a frame depend on how
		// many noise or intensity bands happened to precede it.
		int cur_sf = global_gain;
		int noise_sf = global_gain;
		int intensity_sf = 0;
		bool noise_seen = false;
		for (int s = 0; s < max_sfb; ++s) {
			int band = sect_cb[ch][s];
			if (band == 0) {
				sf[ch][s] = 0;
				continue;
			}
			if (band == 13) {                   // NOISE_BT
				noise_sf += noise_seen
					? AAC_DecodeScalefactor(&br)
					: ((int)AACBitReader_GetBits(&br, 9) - 256);
				noise_seen = true;
				sf[ch][s] = (int16)noise_sf;
				continue;
			}
			if (band == 14 || band == 15) {     // INTENSITY_BT2 / INTENSITY_BT
				intensity_sf += AAC_DecodeScalefactor(&br);
				sf[ch][s] = (int16)intensity_sf;
				continue;
			}
			cur_sf += AAC_DecodeScalefactor(&br);
			sf[ch][s] = (int16)cur_sf;
		}

		int pulse_present = AACBitReader_Get1Bit(&br);
		if (pulse_present) {
			int pulse_num = AACBitReader_GetBits(&br, 2);
			int pulse_start_sfb = AACBitReader_GetBits(&br, 6);
			for (int p = 0; p <= pulse_num; ++p) {
				AACBitReader_GetBits(&br, 5);
				AACBitReader_GetBits(&br, 4);
			}
		}

		int tns_present = AACBitReader_Get1Bit(&br);
		if (tns_present) {
			// Every filter of the window is coded, and each coefficient loses a bit when
			// coef_compress is set (coef_len = coef_res + 3 - coef_compress, ISO/IEC 14496-3
			// Table 4.48).  Reading a single filter with a fixed coefficient width
			// over-consumed the bitstream whenever n_filt > 1 or a filter was compressed,
			// desynchronising the rest of the frame.
			int n_filt = AACBitReader_GetBits(&br, 2);
			int coef_res = n_filt ? AACBitReader_Get1Bit(&br) : 0;
			tns[ch].n_filt = n_filt;
			tns[ch].coef_res = coef_res;
			for (int filt = 0; filt < n_filt; ++filt) {
				AACTnsFilter& flt = tns[ch].filt[filt];
				flt.length = (int)AACBitReader_GetBits(&br, 6);
				flt.order = (int)AACBitReader_GetBits(&br, 5);
				flt.direction = 0;
				flt.coef_compress = 0;
				if (flt.order > 0) {
					flt.direction = (int)AACBitReader_Get1Bit(&br);
					flt.coef_compress = (int)AACBitReader_Get1Bit(&br);
					int coef_bits = coef_res + 3 - flt.coef_compress;
					int n = flt.order;
					if (n > 32) n = 32;
					for (int o = 0; o < n; ++o) {
						flt.coef[o] = (int)AACBitReader_GetBits(&br, coef_bits);
					}
				}
			}
		}

		int gain_present = AACBitReader_Get1Bit(&br);
		if (gain_present) {
			AACBitReader_GetBits(&br, 2);
		}

		for (int s = 0; s < max_sfb; ++s) {
			int cb = sect_cb[ch][s];
			int sfb_start = swb_offsets[s];
			int sfb_end = swb_offsets[s + 1];
			int sfb_lines = sfb_end - sfb_start;

			if (cb == 0 || cb > 11) {
				for (int k = 0; k < sfb_lines && (sfb_start + k) < 1024; ++k) spec[ch][sfb_start + k] = 0.0f;
				continue;
			}

			const uint16_t* codes = s_aac_spectral_codes[cb - 1];
			const uint8_t* bits = s_aac_spectral_bits[cb - 1];
			int size = s_aac_spectral_sizes[cb - 1];
			const float* vecs = s_aac_codebook_vectors[cb - 1];
			int dim = (cb <= 4) ? 4 : 2;

			float scale = aac_pow2_quarter(sf[ch][s] - 100);

			for (int k = 0; k < sfb_lines; k += dim) {
				if (br.bit_pos >= br.len * 8) break;
				int idx = AAC_DecodeHuffman(&br, codes, bits, size);
				// Substituting index 0 here used to hide a desynchronised bit reader and turn
				// it into plausible-looking noise; a code word that cannot be matched means the
				// frame is not decodable at this point.
				if (idx < 0) return false;

				// An unsigned codebook writes the sign bits of the whole tuple before the escape
				// sequences, the order ISO/IEC 14496-3 4.6.3.3 prescribes: code word, then the
				// sign bits, then the escapes.  The escape is marked by the sentinel 64.0f in the
				// codebook vectors, not by the value 16.0f.  Interleaving sign bits with the
				// escapes, and testing 16.0f, left 64.0f in the spectrum as a real coefficient
				// (64^(4/3) = 256, which is exactly the oversized magnitude seen here) and
				// desynchronised everything after it.
				bool neg[4] = { false, false, false, false };
				if (cb == 3 || cb == 4 || (cb >= 7 && cb <= 11)) {
					for (int d = 0; d < dim; ++d) {
						if (vecs[idx * dim + d] != 0.0f) {
							neg[d] = (AACBitReader_Get1Bit(&br) != 0);
						}
					}
				}

				for (int d = 0; d < dim; ++d) {
					float mag = aac_fabs(vecs[idx * dim + d]);
					// The codebook vector tables already hold |q|^(4/3), so the inverse
					// quantization of a coded coefficient is just its table value.  Only the ESC
					// codebook's escape word carries a raw magnitude, and that one still needs the
					// 4/3 power.  Applying it to the table values as well scaled every band by a
					// factor that grew with the coefficient, which is what pushed the output 44%
					// above the reference level.
					bool escaped = false;
					if (cb == 11 && mag == 64.0f) {
						int n_ones = 0;
						while (AACBitReader_BitsLeft(&br) > 0 && AACBitReader_Get1Bit(&br) == 1) {
							// The escape sequence is at most 11111111 0 + 12 bits, so more
							// consecutive ones than that mean the reader is already off track.
							if (++n_ones > 8) return false;
						}
						if (AACBitReader_BitsLeft(&br) < (size_t)(n_ones + 4)) return false;
						int esc = AACBitReader_GetBits(&br, n_ones + 4);
						mag = (float)((1 << (n_ones + 4)) + esc);
						escaped = true;
					}

					float iq = (escaped ? aac_pow43(mag) : mag) * scale;
					if (neg[d]) iq = -iq;
					if (sfb_start + k + d < 1024) {
						spec[ch][sfb_start + k + d] = iq;
					}
				}
			}
		}
	}

	for (int s = 0; s < max_sfb; ++s) {
		if (ms_used[s]) {
			int sfb_start = swb_offsets[s];
			int sfb_end = swb_offsets[s + 1];
			for (int i = sfb_start; i < sfb_end; ++i) {
				float L = spec[0][i];
				float R = spec[1][i];
				spec[0][i] = L + R;
				spec[1][i] = L - R;
			}
		}
	}

	// Temporal noise shaping is the last thing applied to the spectrum before the filterbank
	// (ISO/IEC 14496-3 4.6.9.3).  It was parsed but never applied, so every frame that used it
	// came out with the wrong spectral envelope.
	for (int ch = 0; ch < 2; ++ch) {
		if (tns[ch].n_filt > 0) AAC_TnsApply(spec[ch], &tns[ch], (int)max_sfb);
	}

	// The IMDCT output is windowed with the shape and sequence this frame signalled.
	AAC_BuildFrameWindow(win_seq, win_shape);

	for (int ch = 0; ch < 2; ++ch) {
		float time_buf[2048];
		AAC_IMDCT_2048(spec[ch], time_buf);

		for (int i = 0; i < 2048; ++i) {
			time_buf[i] *= aac_frame_win[i];
		}

		for (int i = 0; i < 1024; ++i) {
			float sample = time_buf[i] + state->ch[ch].overlap[i];
			state->ch[ch].overlap[i] = time_buf[i + 1024];

			// The IMDCT above carries the 2/N of ISO/IEC 14496-3, so its output already is the
			// reconstructed time signal on the same scale as the coded PCM.  Scaling it by 32767
			// a second time saturated every non-silent frame.
			int pcm = (int)(sample);
			if (pcm < -32768) pcm = -32768;
			if (pcm > 32767) pcm = 32767;
			pcm_out_interleaved[i * 2 + ch] = (int16)pcm;
		}
	}

	return true;
}

	// Raw AAC access units carry no framing of their own, so the stream walks the frame table of
	// the container that owns them.  One access unit decodes to 1024 interleaved stereo samples.
	class AACStream : public uni::IAudioStream {
	private:
		uni::StorageTrait* m_storage;
		uni::trait::Malloc* m_alloc;
		const uni::AACRawFrame* m_frames;
		uint32 m_frame_count;
		uint32 m_frame_cap;
		bool   m_owns_frames;
		uint32 m_curr_frame;
		uni::AudioInfo m_info;

		AACDecoderState m_state;
		int16 m_pcm[2048];
		uint32 m_pcm_avail;
		uint32 m_pcm_off;

		byte* m_packet;
		uint32 m_packet_cap;

		bool LoadFrame(uint32 index) {
			if (index >= m_frame_count || !m_frames) return false;
			const uni::AACRawFrame& f = m_frames[index];
			if (f.size == 0) return false;
			if (f.size > m_packet_cap) {
				byte* bigger = (byte*)m_alloc->allocate(f.size, 3);
				if (!bigger) return false;
				if (m_packet) m_alloc->deallocate(m_packet, m_packet_cap);
				m_packet = bigger;
				m_packet_cap = f.size;
			}
			return StorageReadExact(*m_storage, f.offset, m_packet, f.size);
		}

	public:
		AACStream(
			uni::StorageTrait& storage,
			const uni::AACRawFrame* frames,
			uint32 frame_count,
			uint32 frame_cap,
			bool own_frames,
			uint32 sample_rate,
			uint32 channels,
			uni::trait::Malloc& allocator
		) : m_storage(&storage), m_alloc(&allocator), m_frames(frames), m_frame_count(frame_count),
			m_frame_cap(frames ? frame_cap : 0), m_owns_frames(own_frames), m_curr_frame(0),
			m_pcm_avail(0), m_pcm_off(0), m_packet(nullptr), m_packet_cap(0) {
			MemSet(&m_state, 0, sizeof(m_state));
			m_info = uni::AudioInfo{};
			m_info.format.sample_format = uni::AudioSampleFormat::S16LE;
			m_info.format.channels = (uint16)(channels ? channels : 2);
			m_info.format.sample_rate = sample_rate;
			m_info.containerFormat = uni::AudioContainerFormat::AAC;
			m_info.bitsPerSample = 16;
			m_info.totalSamples = frame_count * 1024;
			m_info.durationMs = sample_rate
				? (uint32)(((uint64)frame_count * 1024 * 1000) / sample_rate)
				: 0;
		}

		virtual void Release() override {
			uni::trait::Malloc* alloc = m_alloc;
			uint32 cap = m_frame_cap;
			const uni::AACRawFrame* frames = m_frames;
			bool owned = m_owns_frames;
			byte* packet = m_packet;
			uint32 packet_cap = m_packet_cap;
			this->~AACStream();
			if (packet) alloc->deallocate(packet, packet_cap);
			if (owned && frames) alloc->deallocate((void*)frames, cap * sizeof(uni::AACRawFrame));
			alloc->deallocate(this);
		}

		virtual uni::AudioResult GetInfo(uni::AudioInfo& outInfo) const override {
			outInfo = m_info;
			return uni::AudioResult::OK;
		}

		virtual uni::AudioResult ReadSamples(void* destBuffer, uint32 maxBytes, uint32& bytesRead) override {
			bytesRead = 0;
			if (!destBuffer || maxBytes == 0) return uni::AudioResult::InvalidArgument;

			byte* out = (byte*)destBuffer;
			while (maxBytes > 0) {
				if (m_pcm_avail > 0) {
					uint32 to_copy = (maxBytes < m_pcm_avail) ? maxBytes : m_pcm_avail;
					MemCopyN(out, (byte*)m_pcm + m_pcm_off, to_copy);
					out += to_copy;
					bytesRead += to_copy;
					maxBytes -= to_copy;
					m_pcm_off += to_copy;
					m_pcm_avail -= to_copy;
					continue;
				}
				if (m_curr_frame >= m_frame_count) break;

				uint32 size = m_frames[m_curr_frame].size;
				// A rejected access unit becomes silence instead of a short read, so one bad
				// frame cannot shift the whole stream out of step with the video.
				bool ok = LoadFrame(m_curr_frame) && DecodeAAC_CPE(&m_state, m_packet, size, m_pcm);
				if (!ok) MemSet(m_pcm, 0, 1024 * 2 * sizeof(int16));
				++m_curr_frame;
				m_pcm_avail = 1024 * 2 * sizeof(int16);
				m_pcm_off = 0;
			}
			if (bytesRead == 0 && m_curr_frame >= m_frame_count) return uni::AudioResult::EndOfStream;
			return uni::AudioResult::OK;
		}

		virtual uni::AudioResult Seek(uint32 sampleIndex) override {
			uint32 frame = sampleIndex / 1024;
			if (frame > m_frame_count) frame = m_frame_count;
			m_curr_frame = frame;
			m_pcm_avail = 0;
			m_pcm_off = 0;
			// The overlap held from the previous frame belongs to the old position.
			MemSet(&m_state, 0, sizeof(m_state));
			return uni::AudioResult::OK;
		}
	};

	static const char* const AAC_EXTENSIONS[] = { ".aac", ".adts", nullptr };

	// ADTS frame header (ISO/IEC 13818-7): 12-bit sync word, then the sampling frequency index
	// and channel configuration.  Every frame carries 1024 samples in the LC profile handled here.
	static bool AAC_ParseADTSHeader(const byte* h, uint32& sample_rate, uint32& channels, uint32& frame_len) {
		if (!h || h[0] != 0xFF || (h[1] & 0xF0) != 0xF0) return false;
		static const uint32 rates[16] = {
			96000, 88200, 64000, 48000, 44100, 32000, 24000, 22050,
			16000, 12000, 11025, 8000, 7350, 0, 0, 0
		};
		sample_rate = rates[(uint32)(h[2] >> 2) & 0x0F];
		if (sample_rate == 0) return false;
		channels = ((uint32)(h[2] & 0x01) << 2) | ((uint32)(h[3] >> 6) & 0x03);
		frame_len = ((uint32)(h[3] & 0x03) << 11) | ((uint32)h[4] << 3) | ((uint32)(h[5] >> 5) & 0x07);
		return frame_len >= 7;
	}

