#!/usr/bin/perl
# ASCII Perl TAB4 LF

use strict;
use warnings;
use FindBin;
use File::Path qw(make_path);

my $input = "$FindBin::Bin/instructions.dat";
my $source_directory = "$FindBin::Bin/../data";
my $header_directory = "$FindBin::Bin/../../../../../../inc/cpp/Lango/Archend/riscv/data";
my $source_path = "$source_directory/Instructions-riscv.cpp";
my $header_path = "$header_directory/Instructions-riscv.hpp";

my %formats = map { $_ => 1 } qw(
	Upper Jump IndirectJump Branch Load Store Immediate Shift Register
	ImmediateWord ShiftWord RegisterWord System
);
my %operands = map { $_ => 1 } qw(
	None RdImmediate RdTarget RdIndirectTarget RsRsTarget RdAddress RsAddress
	RdRsImmediateOptional RdRsRsOptional
);
my %extensions = map { $_ => 1 } qw(I);

open my $input_file, '<', $input or die "unable to open $input: $!\n";
my @instructions;
my %names;
my %enums;
my $line_number = 0;
while (my $line = <$input_file>) {
	$line_number++;
	$line =~ s/\r?\n$//;
	$line =~ s/;.*$//;
	next if $line =~ /^\s*$/;
	my @fields = split /\s+/, $line;
	die "$input:$line_number: expected 9 fields\n" unless @fields == 9;
	my ($name, $enum, $format, $operand, $fixed, $xlen, $extension,
		$signed, $unsigned) = @fields;
	die "$input:$line_number: invalid instruction name\n"
		unless $name =~ /^[A-Z][A-Z0-9]*$/;
	die "$input:$line_number: invalid enum name\n"
		unless $enum =~ /^[A-Z][A-Za-z0-9]*$/;
	die "$input:$line_number: duplicate instruction $name\n" if $names{$name}++;
	die "$input:$line_number: duplicate enum $enum\n" if $enums{$enum}++;
	die "$input:$line_number: unknown format $format\n" unless $formats{$format};
	die "$input:$line_number: unknown operand form $operand\n" unless $operands{$operand};
	die "$input:$line_number: invalid fixed bits $fixed\n"
		unless $fixed =~ /^0x[0-9a-fA-F]{8}$/;
	die "$input:$line_number: invalid XLEN $xlen\n"
		unless $xlen eq '32' || $xlen eq '64' || $xlen eq '32|64';
	die "$input:$line_number: unknown extension $extension\n"
		unless $extensions{$extension};
	push @instructions, {
		name => $name, enum => $enum, format => $format, operand => $operand,
		fixed => lc($fixed), xlen => $xlen, extension => $extension,
		signed => $signed, unsigned => $unsigned, line => $line_number
	};
}
close $input_file;

for my $instruction (@instructions) {
	for my $variant_name (qw(signed unsigned)) {
		my $variant = $instruction->{$variant_name};
		next if $variant eq '-';
		die "$input:$instruction->{line}: unknown $variant_name variant $variant\n"
			unless $enums{$variant};
	}
	my $has_signed = $instruction->{signed} ne '-';
	my $has_unsigned = $instruction->{unsigned} ne '-';
	die "$input:$instruction->{line}: incomplete signedness variants\n"
		if $has_signed != $has_unsigned;
}

make_path($source_directory, $header_directory);

open my $header, '>', $header_path or die "unable to write $header_path: $!\n";
print $header <<'HEADER';
// ASCII C++11 TAB4 LF
// Generated by make-instructions.pl from instructions.dat. Do not edit.

#ifndef UNISYM_LANGO_ARCHEND_RISCV_DATA_INSTRUCTIONS_HPP
#define UNISYM_LANGO_ARCHEND_RISCV_DATA_INSTRUCTIONS_HPP

#include <stdint.h>

namespace uni::lango {

enum class RISCVOpcode : uint16_t {
	None,
HEADER
for my $instruction (@instructions) {
	print $header "\t$instruction->{enum},\n";
}
print $header <<'HEADER';
	Count
};

enum class RISCVEncodingFormat : uint8_t {
	Upper,
	Jump,
	IndirectJump,
	Branch,
	Load,
	Store,
	Immediate,
	Shift,
	Register,
	ImmediateWord,
	ShiftWord,
	RegisterWord,
	System
};

enum class RISCVOperandForm : uint8_t {
	None,
	RdImmediate,
	RdTarget,
	RdIndirectTarget,
	RsRsTarget,
	RdAddress,
	RsAddress,
	RdRsImmediateOptional,
	RdRsRsOptional
};

enum class RISCVExtension : uint32_t {
	I = UINT32_C(1) << 0
};

enum class RISCVXLen : uint8_t {
	Bits32 = 1,
	Bits64 = 2
};

struct RISCVInstructionInfo {
	const char* name;
	RISCVOpcode opcode;
	RISCVEncodingFormat format;
	RISCVOperandForm operands;
	uint32_t fixed_bits;
	uint32_t required_extensions;
	uint8_t xlen;
	RISCVOpcode signed_variant;
	RISCVOpcode unsigned_variant;
};

const RISCVInstructionInfo* FindRISCVInstruction(const char* name);
const RISCVInstructionInfo& DumpRISCVInstruction(RISCVOpcode opcode);
bool SupportsRISCVXLen(const RISCVInstructionInfo& instruction, int bits);

}

#endif
HEADER
close $header;

open my $source, '>', $source_path or die "unable to write $source_path: $!\n";
print $source <<'SOURCE';
// ASCII C++11 TAB4 LF
// Generated by make-instructions.pl from instructions.dat. Do not edit.

#include "../../../../../../inc/c/ustring.h"
#include "../../../../../../inc/cpp/Lango/Archend/riscv/data/Instructions-riscv.hpp"

namespace uni::lango {

namespace {

const RISCVInstructionInfo Instructions[] = {
	{"", RISCVOpcode::None, RISCVEncodingFormat::System,
		RISCVOperandForm::None, 0, 0, 0,
		RISCVOpcode::None, RISCVOpcode::None},
SOURCE
for my $instruction (@instructions) {
	my $xlen = $instruction->{xlen} eq '32' ?
		'static_cast<uint8_t>(RISCVXLen::Bits32)' :
		$instruction->{xlen} eq '64' ?
		'static_cast<uint8_t>(RISCVXLen::Bits64)' :
		'static_cast<uint8_t>(RISCVXLen::Bits32) | static_cast<uint8_t>(RISCVXLen::Bits64)';
	my $signed = $instruction->{signed} eq '-' ? 'None' : $instruction->{signed};
	my $unsigned = $instruction->{unsigned} eq '-' ? 'None' : $instruction->{unsigned};
	my $name = lc($instruction->{name});
	print $source "\t{\"$name\", RISCVOpcode::$instruction->{enum},\n";
	print $source "\t\tRISCVEncodingFormat::$instruction->{format}, RISCVOperandForm::$instruction->{operand},\n";
	print $source "\t\tUINT32_C($instruction->{fixed}), static_cast<uint32_t>(RISCVExtension::$instruction->{extension}),\n";
	print $source "\t\t$xlen, RISCVOpcode::$signed, RISCVOpcode::$unsigned},\n";
}
print $source <<'SOURCE';
};

static_assert(sizeof(Instructions) / sizeof(Instructions[0]) ==
	static_cast<unsigned>(RISCVOpcode::Count),
	"RISC-V instruction table does not match RISCVOpcode");

const uint16_t InstructionNameOrder[] = {
SOURCE
my @name_order = sort {
	$instructions[$a]{name} cmp $instructions[$b]{name}
} 0 .. $#instructions;
for my $index (@name_order) {
	print $source "\tstatic_cast<uint16_t>(RISCVOpcode::$instructions[$index]{enum}),\n";
}
print $source <<'SOURCE';
};

}

const RISCVInstructionInfo* FindRISCVInstruction(const char* name)
{
	size_t lower = 0;
	size_t upper = sizeof(InstructionNameOrder) /
		sizeof(InstructionNameOrder[0]);
	while (lower < upper) {
		size_t middle = lower + (upper - lower) / 2;
		const RISCVInstructionInfo& instruction =
			Instructions[InstructionNameOrder[middle]];
		int comparison = StrCompareInsensitive(name, instruction.name);
		if (!comparison) return &instruction;
		if (comparison < 0) upper = middle;
		else lower = middle + 1;
	}
	return nullptr;
}

const RISCVInstructionInfo& DumpRISCVInstruction(RISCVOpcode opcode)
{
	unsigned index = static_cast<unsigned>(opcode);
	if (index >= static_cast<unsigned>(RISCVOpcode::Count)) index = 0;
	return Instructions[index];
}

bool SupportsRISCVXLen(const RISCVInstructionInfo& instruction, int bits)
{
	uint8_t required = bits == 32 ? static_cast<uint8_t>(RISCVXLen::Bits32) :
		bits == 64 ? static_cast<uint8_t>(RISCVXLen::Bits64) : 0;
	return required && (instruction.xlen & required);
}

}
SOURCE
close $source;

print "generated $header_path\n";
print "generated $source_path\n";
