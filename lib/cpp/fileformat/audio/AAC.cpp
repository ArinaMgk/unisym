	// Byte-wise read over a StorageTrait; the block interface below is not required to be
	// random-access at this granularity and every container helper does the same thing.
	static bool StorageReadExact(uni::StorageTrait& storage, uint64 offset, void* dst, size_t len) {
		if (len == 0) return true;
		byte* p = (byte*)dst;
		for (size_t i = 0; i < len; ++i) {
			int b = storage[offset + i];
			if (b < 0) return false;
			p[i] = (byte)b;
		}
		return true;
	}

