#!/usr/bin/perl
# ASCII Perl TAB4 LF

use strict;
use warnings;
use FindBin;
use File::Path qw(make_path);

my $input_path = "$FindBin::Bin/instructions.dat";
my $source_directory = "$FindBin::Bin/../data";
my $header_directory = "$FindBin::Bin/../../../../../../inc/cpp/Lango/Archend/arm32/data";
my $source_path = "$source_directory/Instructions-arm32.cpp";
my $header_path = "$header_directory/Instructions-arm32.hpp";

my %formats = map { $_ => 1 } qw(
	Fixed Branch RegisterBranch DataProcessing Compare LoadStore LoadStoreExtra
);
my %operands = map { $_ => 1 } qw(
	None Target Register RdRnOperand2 RnOperand2 RtAddress
);

open my $input, '<', $input_path or die "unable to open $input_path: $!\n";
my @instructions;
my %enums;
my $line_number = 0;
while (my $line = <$input>) {
	$line_number++;
	$line =~ s/\r?\n$//;
	$line =~ s/;.*$//;
	next if $line =~ /^\s*$/;
	my @fields = split /\s+/, $line;
	die "$input_path:$line_number: expected 7 fields\n" unless @fields == 7;
	my ($name, $enum, $format, $operands, $fixed, $supports_s, $access) = @fields;
	die "$input_path:$line_number: invalid instruction name\n"
		unless $name =~ /^[A-Z][A-Z0-9]*$/;
	die "$input_path:$line_number: invalid enum name\n"
		unless $enum =~ /^[A-Z][A-Za-z0-9]*$/;
	die "$input_path:$line_number: duplicate enum $enum\n" if $enums{$enum}++;
	die "$input_path:$line_number: unknown format $format\n" unless $formats{$format};
	die "$input_path:$line_number: unknown operands $operands\n" unless $operands{$operands};
	die "$input_path:$line_number: invalid fixed bits\n"
		unless $fixed =~ /^0x[0-9a-fA-F]{8}$/;
	die "$input_path:$line_number: invalid S flag\n"
		unless $supports_s eq '0' || $supports_s eq '1';
	die "$input_path:$line_number: invalid access size\n"
		unless $access =~ /^(?:0|1|2|4)$/;
	push @instructions, {
		name => lc($name), enum => $enum, format => $format,
		operands => $operands, fixed => lc($fixed),
		supports_s => $supports_s, access => $access
	};
}
close $input;

make_path($source_directory, $header_directory);

open my $header, '>', $header_path or die "unable to write $header_path: $!\n";
print $header <<'HEADER';
// ASCII C++11 TAB4 LF
// Generated by make-instructions.pl from instructions.dat. Do not edit.

#ifndef UNISYM_LANGO_ARCHEND_ARM32_DATA_INSTRUCTIONS_HPP
#define UNISYM_LANGO_ARCHEND_ARM32_DATA_INSTRUCTIONS_HPP

#include "../../../Archend.hpp"

namespace uni::lango {

enum class ARM32Opcode : uint16_t {
	None,
HEADER
for my $instruction (@instructions) {
	print $header "\t$instruction->{enum},\n";
}
print $header <<'HEADER';
	Count
};

enum class ARM32EncodingFormat : uint8_t {
	Fixed,
	Branch,
	RegisterBranch,
	DataProcessing,
	Compare,
	LoadStore,
	LoadStoreExtra
};

enum class ARM32OperandForm : uint8_t {
	None,
	Target,
	Register,
	RdRnOperand2,
	RnOperand2,
	RtAddress
};

struct ARM32InstructionInfo {
	const char* name;
	ARM32Opcode opcode;
	ARM32EncodingFormat format;
	ARM32OperandForm operands;
	uint32_t fixed;
	bool supports_set_flags;
	uint8_t access_size;
};

const ARM32InstructionInfo* FindARM32Instructions(
	const char* name, size_t& count);
const ARM32InstructionInfo& DumpARM32Instruction(ARM32Opcode opcode);

}

#endif
HEADER
close $header;

open my $source, '>', $source_path or die "unable to write $source_path: $!\n";
print $source <<'SOURCE';
// ASCII C++11 TAB4 LF
// Generated by make-instructions.pl from instructions.dat. Do not edit.

#include "../../../../../../inc/c/ustring.h"
#include "../../../../../../inc/cpp/Lango/Archend/arm32/data/Instructions-arm32.hpp"

namespace uni::lango {

namespace {

const ARM32InstructionInfo Instructions[] = {
	{"", ARM32Opcode::None, ARM32EncodingFormat::Fixed,
		ARM32OperandForm::None, 0, false, 0},
SOURCE
for my $instruction (@instructions) {
	my $supports_s = $instruction->{supports_s} ? 'true' : 'false';
	print $source "\t{\"$instruction->{name}\", ARM32Opcode::$instruction->{enum},\n";
	print $source "\t\tARM32EncodingFormat::$instruction->{format}, ARM32OperandForm::$instruction->{operands},\n";
	print $source "\t\tUINT32_C($instruction->{fixed}), $supports_s, $instruction->{access}},\n";
}
print $source <<'SOURCE';
};

}

const ARM32InstructionInfo* FindARM32Instructions(
	const char* name, size_t& count)
{
	const ARM32InstructionInfo* first = nullptr;
	count = 0;
	for (size_t index = 1; index < numsof(Instructions); index++) {
		if (StrCompareInsensitive(name, Instructions[index].name)) {
			if (first) break;
			continue;
		}
		if (!first) first = &Instructions[index];
		count++;
	}
	return first;
}

const ARM32InstructionInfo& DumpARM32Instruction(ARM32Opcode opcode)
{
	size_t index = static_cast<size_t>(opcode);
	if (index >= numsof(Instructions)) index = 0;
	return Instructions[index];
}

}
SOURCE
close $source;
