#!/usr/bin/perl
# ASCII Perl TAB4 LF

use strict;
use warnings;
use FindBin;
use File::Path qw(make_path);

my $input_path = "$FindBin::Bin/instructions.dat";
my $source_directory = "$FindBin::Bin/../data";
my $header_directory = "$FindBin::Bin/../../../../../../inc/cpp/Lango/Archend/arm64/data";
my $source_path = "$source_directory/Instructions-arm64.cpp";
my $header_path = "$header_directory/Instructions-arm64.hpp";

my %formats = map { $_ => 1 } qw(
	Fixed Branch ConditionalBranch RegisterBranch AddSubRegister
	AddSubImmediate CompareRegister CompareImmediate LogicalRegister LoadStore
);
my %operands = map { $_ => 1 } qw(
	None Target Register RegisterOptional RdRnRm RdRnImmediate RnRm
	RnImmediate RtAddress
);

open my $input, '<', $input_path or die "unable to open $input_path: $!\n";
my @instructions;
my %enums;
my $line_number = 0;
while (my $line = <$input>) {
	$line_number++;
	$line =~ s/\r?\n$//;
	$line =~ s/;.*$//;
	next if $line =~ /^\s*$/;
	my @fields = split /\s+/, $line;
	die "$input_path:$line_number: expected 7 fields\n" unless @fields == 7;
	my ($name, $enum, $format, $operands, $fixed32, $fixed64, $access) = @fields;
	die "$input_path:$line_number: invalid instruction name\n"
		unless $name =~ /^[A-Z][A-Z0-9]*(?:\.[A-Z0-9]+)*$/;
	die "$input_path:$line_number: invalid enum name\n"
		unless $enum =~ /^[A-Z][A-Za-z0-9]*$/;
	die "$input_path:$line_number: duplicate enum $enum\n" if $enums{$enum}++;
	die "$input_path:$line_number: unknown format $format\n" unless $formats{$format};
	die "$input_path:$line_number: unknown operands $operands\n" unless $operands{$operands};
	for my $fixed ($fixed32, $fixed64) {
		die "$input_path:$line_number: invalid fixed bits\n"
			unless $fixed eq '-' || $fixed =~ /^0x[0-9a-fA-F]{8}$/;
	}
	die "$input_path:$line_number: invalid access size\n"
		unless $access =~ /^(?:0|1|2|4|8|4\|8)$/;
	push @instructions, {
		name => lc($name), enum => $enum, format => $format,
		operands => $operands, fixed32 => lc($fixed32),
		fixed64 => lc($fixed64), access => $access
	};
}
close $input;

make_path($source_directory, $header_directory);

open my $header, '>', $header_path or die "unable to write $header_path: $!\n";
print $header <<'HEADER';
// ASCII C++11 TAB4 LF
// Generated by make-instructions.pl from instructions.dat. Do not edit.

#ifndef UNISYM_LANGO_ARCHEND_ARM64_DATA_INSTRUCTIONS_HPP
#define UNISYM_LANGO_ARCHEND_ARM64_DATA_INSTRUCTIONS_HPP

#include "../../../Archend.hpp"

namespace uni::lango {

enum class ARM64Opcode : uint16_t {
	None,
HEADER
for my $instruction (@instructions) {
	print $header "\t$instruction->{enum},\n";
}
print $header <<'HEADER';
	Count
};

enum class ARM64EncodingFormat : uint8_t {
	Fixed,
	Branch,
	ConditionalBranch,
	RegisterBranch,
	AddSubRegister,
	AddSubImmediate,
	CompareRegister,
	CompareImmediate,
	LogicalRegister,
	LoadStore
};

enum class ARM64OperandForm : uint8_t {
	None,
	Target,
	Register,
	RegisterOptional,
	RdRnRm,
	RdRnImmediate,
	RnRm,
	RnImmediate,
	RtAddress
};

struct ARM64InstructionInfo {
	const char* name;
	ARM64Opcode opcode;
	ARM64EncodingFormat format;
	ARM64OperandForm operands;
	uint32_t fixed32;
	uint32_t fixed64;
	uint8_t access32;
	uint8_t access64;
};

const ARM64InstructionInfo* FindARM64Instructions(
	const char* name, size_t& count);
const ARM64InstructionInfo& DumpARM64Instruction(ARM64Opcode opcode);

}

#endif
HEADER
close $header;

open my $source, '>', $source_path or die "unable to write $source_path: $!\n";
print $source <<'SOURCE';
// ASCII C++11 TAB4 LF
// Generated by make-instructions.pl from instructions.dat. Do not edit.

#include "../../../../../../inc/c/ustring.h"
#include "../../../../../../inc/cpp/Lango/Archend/arm64/data/Instructions-arm64.hpp"

namespace uni::lango {

namespace {

const ARM64InstructionInfo Instructions[] = {
	{"", ARM64Opcode::None, ARM64EncodingFormat::Fixed,
		ARM64OperandForm::None, 0, 0, 0, 0},
SOURCE
for my $instruction (@instructions) {
	my $fixed32 = $instruction->{fixed32} eq '-' ? '0' : "UINT32_C($instruction->{fixed32})";
	my $fixed64 = $instruction->{fixed64} eq '-' ? '0' : "UINT32_C($instruction->{fixed64})";
	my ($access32, $access64) = $instruction->{access} eq '4|8' ? (4, 8) :
		($instruction->{fixed32} eq '-' ? 0 : $instruction->{access},
		 $instruction->{fixed64} eq '-' ? 0 : $instruction->{access});
	print $source "\t{\"$instruction->{name}\", ARM64Opcode::$instruction->{enum},\n";
	print $source "\t\tARM64EncodingFormat::$instruction->{format}, ARM64OperandForm::$instruction->{operands},\n";
	print $source "\t\t$fixed32, $fixed64, $access32, $access64},\n";
}
print $source <<'SOURCE';
};

}

const ARM64InstructionInfo* FindARM64Instructions(
	const char* name, size_t& count)
{
	const ARM64InstructionInfo* first = nullptr;
	count = 0;
	for (size_t index = 1; index < numsof(Instructions); index++) {
		if (StrCompareInsensitive(name, Instructions[index].name)) {
			if (first) break;
			continue;
		}
		if (!first) first = &Instructions[index];
		count++;
	}
	return first;
}

const ARM64InstructionInfo& DumpARM64Instruction(ARM64Opcode opcode)
{
	size_t index = static_cast<size_t>(opcode);
	if (index >= numsof(Instructions)) index = 0;
	return Instructions[index];
}

}
SOURCE
close $source;
